    private void configurarTabla() {
        tablaProductos.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tablaProductos.setRowHeight(28);
        tablaProductos.getTableHeader().setFont(tablaProductos.getTableHeader().getFont().deriveFont(Font.BOLD));

        tablaProductos.getColumnModel().getColumn(0).setPreferredWidth(45);
        tablaProductos.getColumnModel().getColumn(1).setPreferredWidth(90);
        tablaProductos.getColumnModel().getColumn(2).setPreferredWidth(225);
        tablaProductos.getColumnModel().getColumn(3).setPreferredWidth(65);
        tablaProductos.getColumnModel().getColumn(4).setPreferredWidth(110);

        DefaultTableCellRenderer alineadoDerecha = new DefaultTableCellRenderer();
        alineadoDerecha.setHorizontalAlignment(SwingConstants.RIGHT);
        tablaProductos.getColumnModel().getColumn(3).setCellRenderer(alineadoDerecha);
        DefaultTableCellRenderer centrado = new DefaultTableCellRenderer();
        centrado.setHorizontalAlignment(SwingConstants.CENTER);
        tablaProductos.getColumnModel().getColumn(0).setCellRenderer(centrado);

        NumberFormat formatoPrecio = NumberFormat.getCurrencyInstance(Locale.of("es", "AR"));
        DefaultTableCellRenderer celdaPrecio = new DefaultTableCellRenderer() {
            @Override
            protected void setValue(Object valor) {
                setText(valor == null ? "" : formatoPrecio.format(valor));   // 2500.0 -> $ 2.500,00
            }
        };
        celdaPrecio.setHorizontalAlignment(SwingConstants.RIGHT);
        tablaProductos.getColumnModel().getColumn(4).setCellRenderer(celdaPrecio);
    }

